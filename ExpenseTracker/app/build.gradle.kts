android {
    namespace = "com.expensetracker.app"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.expensetracker.app"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0"
    }

    signingConfigs {
        getByName("debug") {
            // Checked into version control (app is debug-only for now, nothing secret in this
            // key) so every build — local or CI — signs with the same certificate. Without this,
            // AGP auto-generates a random ~/.android/debug.keystore per machine; on CI's ephemeral
            // runners that meant every workflow run got a different signature, so installing a
            // newer debug APK over an older one failed as a signature mismatch and forced an
            // uninstall (wiping local data) before Android would let the update through.
            storeFile = rootProject.file("debug.keystore")
            storePassword = "android"
            keyAlias = "androiddebugkey"
            keyPassword = "android"
        }
        create("release") {
            // Unlike the debug key, a real release key must never be checked in (whoever holds it
            // controls every future update users can install over the current one) — so it's read
            // from a git-ignored properties file instead. Deliberately left with no storeFile when
            // that file is absent rather than falling back to the debug key or skipping signing:
            // assembleRelease should fail loudly with a clear "keystore not set" error, not
            // silently produce an unsigned/unshippable APK. See release.keystore.properties.example.
            val propsFile = rootProject.file("release.keystore.properties")
            if (propsFile.exists()) {
                val props = Properties().apply { propsFile.inputStream().use { load(it) } }
                storeFile = rootProject.file(props.getProperty("storeFile"))
                storePassword = props.getProperty("storePassword")
                keyAlias = props.getProperty("keyAlias")
                keyPassword = props.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.getByName("release")
        }
        debug {
            applicationIdSuffix = ".debug"
            signingConfig = signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlin {
        jvmToolchain(17)
    }

    buildFeatures {
        compose = true
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

